#!/usr/bin/env python3
"""Regenerate the reference-results table in docs/simulator.md from a real run.

The table is evidence, so it must be produced by running the scenarios rather
than hand-maintained: a hand-edited table silently goes stale the moment the
controller is tuned, and a stale table is worse than none.  Run this after any
change that affects navigation, and use ``--check`` in CI to catch drift.

Usage
-----
    python scripts/generate_reference_results.py
    python scripts/generate_reference_results.py --check
"""

from __future__ import annotations

import argparse
import pathlib
import re
import sys

REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
DOC_PATH = REPO_ROOT / "docs" / "simulator.md"

TABLE_BEGIN = "<!-- BEGIN GENERATED REFERENCE TABLE -->"
TABLE_END = "<!-- END GENERATED REFERENCE TABLE -->"

sys.path.insert(0, str(REPO_ROOT / "simulator"))


def collect_rows() -> list[dict]:
    """Run every scenario and collect the metrics the table reports."""
    from smart_trolley_sim.scenario import builtin_scenarios
    from smart_trolley_sim.simulation import SimulationEngine

    rows: list[dict] = []
    for index, scenario in enumerate(builtin_scenarios(), start=1):
        engine = SimulationEngine(scenario)
        try:
            metrics = engine.run_to_completion()
        finally:
            engine.close()
        rows.append({
            "index": index,
            "name": scenario.name,
            # Strip the "scenario_NN_" prefix and underscores for the table.
            "label": scenario.name.split("_", 2)[-1].replace("_", " "),
            "drill": not scenario.expect_success,
            "state": metrics.final_state,
            "time": metrics.completion_time_s,
            "travelled": metrics.ground_truth_distance_m,
            "efficiency": metrics.path_efficiency_percent,
            "xte_mean": metrics.mean_cross_track_error_m,
            "xte_max": metrics.max_cross_track_error_m,
            "destination": metrics.destination_error_m,
            "replans": metrics.replan_count,
        })
    return rows


def render_table(rows: list[dict]) -> str:
    header = ("| Scenario | State | Time (s) | Travelled (m) | Efficiency (%) | "
              "Mean / max XTE (m) | Dest. err (m) | Replans |")
    lines = [
        TABLE_BEGIN,
        "<!-- Generated by scripts/generate_reference_results.py - do not edit by hand. -->",
        "",
        header,
        "|---|---|---|---|---|---|---|---|",
    ]
    for row in rows:
        suffix = " (drill)" if row["drill"] else ""
        if row["drill"]:
            cells = (f"{row['state']} | {row['time']:.1f} | {row['travelled']:.2f} | — | — | — | "
                     f"{row['replans']}")
        else:
            cells = (f"{row['state']} | {row['time']:.1f} | {row['travelled']:.2f} | "
                     f"{row['efficiency']:.1f} | {row['xte_mean']:.2f} / {row['xte_max']:.2f} | "
                     f"{row['destination']:.2f} | {row['replans']}")
        lines.append(f"| {row['index']} {row['label']}{suffix} | {cells} |")
    lines.append(TABLE_END)
    return "\n".join(lines)


def apply_to_document(document: str, table: str) -> str:
    """Replace the generated block, inserting it if absent."""
    if TABLE_BEGIN in document and TABLE_END in document:
        pattern = re.compile(
            re.escape(TABLE_BEGIN) + r".*?" + re.escape(TABLE_END), re.DOTALL
        )
        return pattern.sub(lambda _: table, document, count=1)
    raise SystemExit(
        f"{DOC_PATH} does not contain the {TABLE_BEGIN} / {TABLE_END} markers; "
        "add them around the reference table first."
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true",
                        help="do not write; fail when the table is out of date")
    args = parser.parse_args(argv)

    rows = collect_rows()
    table = render_table(rows)
    document = DOC_PATH.read_text(encoding="utf-8")
    updated = apply_to_document(document, table)

    if args.check:
        if updated != document:
            print("[FAIL] docs/simulator.md reference table is out of date; "
                  "run scripts/generate_reference_results.py")
            return 1
        print("[ok] docs/simulator.md reference table is up to date")
        return 0

    DOC_PATH.write_text(updated, encoding="utf-8")
    print(f"updated {DOC_PATH.relative_to(REPO_ROOT)} with {len(rows)} rows")
    for row in rows:
        flag = " (drill)" if row["drill"] else ""
        print(f"  {row['index']:2d} {row['state']:8s} t={row['time']:5.1f}s "
              f"trav={row['travelled']:6.2f} m eff={row['efficiency']:6.1f}% "
              f"xte={row['xte_mean']:.3f}/{row['xte_max']:.3f} dest={row['destination']:.3f}{flag}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
